export function getSnapshotMarketPairs(rwaId: number): RwaMarketPairsData {
  const quote =
    SNAPSHOT_RWA_QUOTES.find((q) => q.rwa_id === rwaId) ?? SNAPSHOT_RWA_QUOTES[0];
  const baseVenues = [
    { exchange_id: 270, name: "Binance", slug: "binance", weight: 0.38, bpsOffset: -2.1 },
    { exchange_id: 521, name: "Bybit", slug: "bybit", weight: 0.24, bpsOffset: 1.4 },
    { exchange_id: 294, name: "OKX", slug: "okx", weight: 0.19, bpsOffset: 0.8 },
    { exchange_id: 311, name: "Uniswap v3", slug: "uniswap-v3", weight: 0.12, bpsOffset: 5.8 },
    { exchange_id: 24, name: "Kraken", slug: "kraken", weight: 0.07, bpsOffset: -4.2 },
  ];

  const market_pairs = baseVenues.map((venue, idx) => {
    const token = quote.tokens[idx % Math.max(1, quote.tokens.length)];
    const sym = token?.symbol ?? `${quote.symbol}X`;
    const price = Number(
      (quote.average_tokenized_price * (1 + venue.bpsOffset / 10_000)).toFixed(4)
    );
    const vol = Math.round(quote.tokenized_volume_24h * venue.weight);
    return {
      exchange: {
        exchange_id: venue.exchange_id,
        name: venue.name,
        slug: venue.slug,
      },
      market_id: 99000 + rwaId * 10 + idx,
      market_pair: `${sym}/USDT`,
      category: venue.slug.includes("uniswap") ? "dex" : "spot",
      fee_type: "percentage",
      market_pair_base: {
        crypto_id: token?.crypto_id ?? 36992,
        symbol: sym,
        exchange_symbol: sym,
        currency_type: "cryptocurrency",
      },
      market_pair_quotes: {
        crypto_id: 825,
        symbol: "USDT",
        exchange_symbol: "USDT",
        currency_type: "cryptocurrency",
      },
      exchange_reported_quotes: {
        price,
        volume_24h_base: price > 0 ? Number((vol / price).toFixed(2)) : 0,
        volume_24h_quote: vol,
        last_updated: SNAPSHOT_TS,
      },
      quotes: [
        {
          crypto_id: 2781,
          symbol: "USD",
          price,
          volume_24h: vol,
          last_updated: SNAPSHOT_TS,
        },
      ],
    };
  });

  return {
    rwa_id: quote.rwa_id,
    name: quote.name,
    symbol: quote.symbol,
    num_market_pairs: market_pairs.length,
    market_pairs,
    total_size: market_pairs.length,
    has_more: false,
  };
}

